"""
Project ECHO — Sigma-Lognormal Neuromotor Model
=================================================
Implements the Kinematic Theory of rapid human movements via the
Sigma-Lognormal model.

The model decomposes continuous mouse movement into a summation of
simple, time-overlapped lognormal primitives generated by neuromuscular
systems. Each primitive is characterized by:
    - D_i  : stroke amplitude
    - t0_i : logarithmic time delay (onset)
    - μ_i  : log-time mean
    - σ_i  : log-time standard deviation (response time variance)

The reconstructed velocity profile is:
    v(t) = Σ_i  D_i / (σ_i * (t - t0_i) * √(2π))
           * exp(-(ln(t - t0_i) - μ_i)² / (2 * σ_i²))

The quality of reconstruction is measured by Signal-to-Noise Ratio (SNR)
which must exceed 24 dB for reliable neuromotor analysis.

Reference:
    Plamondon, R. (1995). A kinematic theory of rapid human movements.
    Part I. Movement representation and generation.
"""

import numpy as np
from typing import List, Tuple, Optional

from feature_extraction.snr_validator import SNRValidator, SNRResult, SNRQuality


from scipy.optimize import curve_fit


class LognormalStroke:
    """Parameters for a single lognormal stroke primitive (6-parameter IDeLog-compatible)."""

    __slots__ = ("amplitude", "t0", "mu", "sigma", "theta_start", "theta_end")

    def __init__(
        self,
        amplitude: float,
        t0: float,
        mu: float,
        sigma: float,
        theta_start: float = 0.0,
        theta_end: float = 0.0,
    ):
        self.amplitude = amplitude  # D_i: stroke amplitude
        self.t0 = t0                # t0_i: onset time (seconds)
        self.mu = mu                # μ_i: log-time mean
        self.sigma = sigma          # σ_i: log-time standard deviation
        self.theta_start = theta_start  # θ_start: starting angular orientation (radians)
        self.theta_end = theta_end      # θ_end: ending angular orientation (radians)


class SigmaLognormalModel:
    """
    Sigma-Lognormal velocity profile decomposition and reconstruction.

    Phase 1 Upgrade: Integrates tiered SNR validation via SNRValidator
    for quality-aware kinematic parameter extraction.
    """

    SNR_TARGET_DB = 24.0  # Legacy threshold (kept for backward compat)

    def __init__(
        self,
        min_strokes: int = 3,
        velocity_threshold: float = 0.01,
        snr_validator: Optional[SNRValidator] = None,
    ):
        """
        Args:
            min_strokes: Minimum number of stroke primitives to extract.
            velocity_threshold: Minimum velocity (px/s) to register a stroke.
            snr_validator: Tiered SNR validator (uses default if None).
        """
        self.min_strokes = min_strokes
        self.velocity_threshold = velocity_threshold
        self._snr_validator = snr_validator or SNRValidator()

    def compute_velocity_profile(
        self, xs: np.ndarray, ys: np.ndarray, ts: np.ndarray
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Compute the instantaneous velocity profile from trajectory data.

        Args:
            xs, ys: 1-D arrays of x and y positions.
            ts: 1-D array of timestamps (seconds, monotonic).

        Returns:
            Tuple of (times, velocities) — both 1-D arrays.
        """
        if len(xs) < 2:
            return np.array([]), np.array([])

        dx = np.diff(xs.astype(np.float64))
        dy = np.diff(ys.astype(np.float64))
        dt = np.diff(ts.astype(np.float64))

        # Avoid division by zero
        dt = np.where(dt == 0, 1e-6, dt)

        vx = dx / dt
        vy = dy / dt
        speed = np.sqrt(vx ** 2 + vy ** 2)

        return ts[1:], speed

    def extract_strokes(
        self, times: np.ndarray, velocities: np.ndarray
    ) -> List[LognormalStroke]:
        """
        Extract lognormal stroke primitives from a velocity profile.
        Provides closed-form initial estimates from peak geometry.
        """
        if len(velocities) < self.min_strokes:
            return []

        strokes = []
        peaks = self._find_velocity_peaks(velocities)

        for i, peak_idx in enumerate(peaks):
            t_p = times[peak_idx]
            v_p = velocities[peak_idx]

            prev_idx = peaks[i - 1] if i > 0 else 0
            onset_idx = prev_idx + int(np.argmin(velocities[prev_idx : peak_idx + 1]))
            t_0 = times[onset_idx]

            dt_p = t_p - t_0
            if dt_p <= 0.05:
                dt_p = 0.31349
                t_0 = max(0.0, t_p - dt_p)

            sigma = 0.40
            mu = float(np.log(dt_p) + (sigma ** 2))
            amplitude = float(1.0863 * v_p * dt_p)

            strokes.append(LognormalStroke(amplitude=amplitude, t0=t_0, mu=mu, sigma=sigma))

        return strokes

    @staticmethod
    def _eval_lognormal_sum(params: np.ndarray, times: np.ndarray, n_strokes: int) -> np.ndarray:
        """Evaluate a sum of lognormals from a flat parameter vector."""
        v = np.zeros_like(times, dtype=np.float64)
        sqrt2pi = np.sqrt(2.0 * np.pi)
        for k in range(n_strokes):
            off = k * 4
            D, t0, mu, sigma = params[off], params[off + 1], params[off + 2], params[off + 3]
            valid = times > t0
            if not np.any(valid):
                continue
            dt = times[valid] - t0
            log_dt = np.log(dt)
            exponent = -((log_dt - mu) ** 2) / (2.0 * sigma ** 2)
            v[valid] += D * np.exp(exponent) / (dt * sigma * sqrt2pi)
        return v

    def _refine_strokes(
        self, strokes: List[LognormalStroke], times: np.ndarray, velocities: np.ndarray
    ) -> List[LognormalStroke]:
        """
        Refine stroke parameters via bounded L-BFGS-B optimization
        to minimize reconstruction MSE. Uses downsampled objective
        for real-time latency compliance.
        """
        from scipy.optimize import minimize

        n_strokes = len(strokes)
        if n_strokes == 0 or n_strokes > 6:
            return strokes  # Skip refinement for noisy/many-stroke trajectories

        # Downsample for speed: use at most 200 evenly-spaced points
        max_pts = 200
        if len(times) > max_pts:
            idx = np.linspace(0, len(times) - 1, max_pts, dtype=int)
            t_ds = times[idx]
            v_ds = velocities[idx]
        else:
            t_ds = times
            v_ds = velocities

        # Pack initial guesses
        x0 = np.array([
            val for s in strokes for val in (s.amplitude, s.t0, s.mu, s.sigma)
        ])

        # Build bounds: D > 0, t0 >= 0 and < peak, mu free, sigma in [0.1, 2.0]
        bounds = []
        for s in strokes:
            t_mode = s.t0 + np.exp(s.mu - s.sigma ** 2)
            bounds.append((1.0, s.amplitude * 5.0))         # D
            bounds.append((0.0, max(0.01, t_mode - 0.01)))  # t0
            bounds.append((s.mu - 2.0, s.mu + 2.0))         # mu
            bounds.append((0.1, 2.0))                        # sigma

        def objective(params):
            v_hat = self._eval_lognormal_sum(params, t_ds, n_strokes)
            return float(np.sum((v_ds - v_hat) ** 2))

        result = minimize(
            objective, x0, method='L-BFGS-B', bounds=bounds,
            options={'maxiter': 100, 'ftol': 1e-10}
        )

        refined = []
        p = result.x
        for k in range(n_strokes):
            off = k * 4
            refined.append(LognormalStroke(
                amplitude=float(p[off]),
                t0=float(p[off + 1]),
                mu=float(p[off + 2]),
                sigma=float(p[off + 3]),
            ))
        return refined

    def reconstruct_velocity(
        self, strokes: List[LognormalStroke], times: np.ndarray
    ) -> np.ndarray:
        """
        Reconstruct the velocity profile from extracted stroke primitives.
        """
        v_reconstructed = np.zeros_like(times, dtype=np.float64)

        for s in strokes:
            valid = times > s.t0
            if not np.any(valid):
                continue
            dt = times[valid] - s.t0
            log_dt = np.log(dt)
            exponent = -((log_dt - s.mu) ** 2) / (2.0 * s.sigma ** 2)
            denom = dt * s.sigma * np.sqrt(2.0 * np.pi)
            v_reconstructed[valid] += s.amplitude * np.exp(exponent) / denom

        return v_reconstructed

    def compute_snr(
        self, original: np.ndarray, reconstructed: np.ndarray
    ) -> float:
        """
        Compute Signal-to-Noise Ratio (dB) between original and
        reconstructed velocity profiles.
        """
        signal_power = np.sum(original ** 2)
        noise_power = np.sum((original - reconstructed) ** 2)

        if noise_power < 1e-12:
            return 100.0  # Perfect reconstruction

        snr = 10.0 * np.log10(signal_power / noise_power)
        return float(snr)

    def analyze_trajectory(
        self, xs: np.ndarray, ys: np.ndarray, ts: np.ndarray
    ) -> dict:
        """
        Full pipeline: trajectory → velocity → strokes → refine → reconstruction → SNR.

        Returns a dict with tiered SNR quality classification:
            snr_quality: 'unsatisfactory' | 'acceptable' | 'good' | 'excellent'
            snr_confidence_weight: 0.0–1.0 confidence for downstream weighting
            snr_pass: bool (legacy, True if snr_db > SNR_TARGET_DB)
            discarded: True if quality is UNSATISFACTORY
        """
        times, velocities = self.compute_velocity_profile(xs, ys, ts)

        if len(velocities) == 0:
            return {
                "stroke_count": 0, "snr_db": 0.0,
                "snr_pass": False, "strokes": [],
                "snr_quality": SNRQuality.UNSATISFACTORY.value,
                "snr_confidence_weight": 0.0,
                "discarded": True,
            }

        strokes = self.extract_strokes(times, velocities)
        strokes = self._refine_strokes(strokes, times, velocities)
        reconstructed = self.reconstruct_velocity(strokes, times)

        # Tiered SNR validation (Phase 1)
        snr_result = self._snr_validator.validate(velocities, reconstructed)

        # If unsatisfactory, return discard flag with empty strokes
        if snr_result.should_discard:
            return {
                "stroke_count": 0,
                "snr_db": snr_result.snr_db,
                "snr_pass": False,
                "snr_quality": snr_result.quality.value,
                "snr_confidence_weight": snr_result.confidence_weight,
                "discarded": True,
                "strokes": [],
            }

        return {
            "stroke_count": len(strokes),
            "snr_db": snr_result.snr_db,
            "snr_pass": snr_result.snr_db > self.SNR_TARGET_DB,
            "snr_quality": snr_result.quality.value,
            "snr_confidence_weight": snr_result.confidence_weight,
            "discarded": False,
            "strokes": [
                {
                    "amplitude": s.amplitude, "t0": s.t0,
                    "mu": s.mu, "sigma": s.sigma,
                    "theta_start": s.theta_start,
                    "theta_end": s.theta_end,
                }
                for s in strokes
            ],
        }


    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _find_velocity_peaks(self, velocities: np.ndarray, max_peaks: int = 8) -> List[int]:
        """Simple peak detection via local maxima, capped to top peaks by amplitude."""
        peaks = []
        for i in range(1, len(velocities) - 1):
            if (velocities[i] > velocities[i - 1]
                    and velocities[i] > velocities[i + 1]
                    and velocities[i] > self.velocity_threshold):
                peaks.append(i)

        # Ensure minimum number of peaks
        if len(peaks) < self.min_strokes:
            # Fall back to equally-spaced segmentation
            indices = np.linspace(1, len(velocities) - 2,
                                  self.min_strokes, dtype=int)
            peaks = indices.tolist()

        # Cap to top peaks by velocity magnitude for performance
        if len(peaks) > max_peaks:
            peaks = sorted(peaks, key=lambda idx: velocities[idx], reverse=True)[:max_peaks]
            peaks.sort()  # Restore temporal order

        return peaks

    def _fit_lognormal(
        self, segment_t: np.ndarray, segment_v: np.ndarray
    ) -> Optional[LognormalStroke]:
        """
        Fit a single lognormal primitive to a velocity segment.
        Uses method-of-moments estimation for robustness.
        """
        if len(segment_v) < 2 or np.max(segment_v) < self.velocity_threshold:
            return None

        t0 = segment_t[0]
        dt = segment_t - t0
        dt = np.where(dt <= 0, 1e-6, dt)

        trapz_fn = getattr(np, 'trapezoid', getattr(np, 'trapz', None))
        amplitude = float(trapz_fn(segment_v, segment_t))

        log_dt = np.log(dt)
        weights = segment_v / (np.sum(segment_v) + 1e-12)
        mu = float(np.sum(weights * log_dt))
        sigma = float(np.sqrt(np.sum(weights * (log_dt - mu) ** 2)))
        sigma = max(sigma, 0.01)  # Prevent degenerate sigma

        return LognormalStroke(
            amplitude=amplitude, t0=t0, mu=mu, sigma=sigma
        )
